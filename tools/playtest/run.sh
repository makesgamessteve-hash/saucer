#!/bin/sh
# SPDX-License-Identifier: MIT
# Assemble and run one playtest:  tools/playtest/run.sh RUN STYLE SEED LIMIT OUTDIR [shots] [-- extra saucer options]
# SHOT_TICKS='[1200]="name", ...' adds screenshots at fixed ticks; STOP_TICKS ends a shots run early.
# Headless by default (telemetry only); "shots" runs the same game in a
# window (Xvfb) at one tick per frame and writes OUTDIR/../shots_playtest.
set -e
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
RUN=$1; STYLE=$2; SEED=$3; LIMIT=$4; OUT=$5; MODE=${6:-headless}
if [ $# -ge 6 ]; then shift 6; else shift $#; fi
[ "$1" = "--" ] && shift
BUILD=${BUILD:-$ROOT/build/game}
SHOTS=${SHOTS_DIR:-/workspace/saucer/shots_playtest/}
mkdir -p "$OUT" "$SHOTS"
SCRIPT="$OUT/$RUN.lua"
{
  echo "-- generated by tools/playtest/run.sh"
  echo "CFG = { run = \"$RUN\", style = \"$STYLE\", limit = $LIMIT, shots = \"$SHOTS\", jam = true, shot_ticks = { ${SHOT_TICKS:-} } }"
  echo "BOT = (function()"; cat "$HERE/bot.lua"; echo "end)()"
  echo "CAREER = (function()"; cat "$HERE/career.lua"; echo "end)()"
  cat "$HERE/$RUN.lua"
} > "$SCRIPT"
UD="$OUT/user-$RUN"; rm -rf "$UD"
if [ "$MODE" = "net" ]; then
  # two processes on loopback: a host (slot 1) and a guest (slot 2)
  PORT=${PORT:-47890}
  T0=$(date +%s.%N)
  "$BUILD/saucer_headless" --root "$ROOT" --user-dir "$UD-host" --seed "$SEED" --host $PORT --script "$SCRIPT" \
    --ticks $((LIMIT + 60000)) "$@" > "$OUT/$RUN.log" 2>&1 &
  HP=$!
  sleep 1
  "$BUILD/saucer_headless" --root "$ROOT" --user-dir "$UD-guest" --join 127.0.0.1:$PORT --script "$SCRIPT" \
    --ticks $((LIMIT + 60000)) "$@" > "$OUT/$RUN.guest.log" 2>&1 || RC=$?
  wait $HP || RC=$?
  T1=$(date +%s.%N)
  echo "PTTIME $(awk "BEGIN{print $T1 - $T0}") s exit ${RC:-0}" >> "$OUT/$RUN.log"
elif [ "$MODE" = "shots" ]; then
  cd "$OUT"
  xvfb-run -a -s "-screen 0 1600x900x24" "$BUILD/saucer" --root "$ROOT" --user-dir "$UD" --seed "$SEED" \
    --windowed --width 1280 --height 720 --script "$SCRIPT" --ticks ${STOP_TICKS:-$((LIMIT + 60000))} "$@" > "$OUT/$RUN.shots.log" 2>&1
else
  T0=$(date +%s.%N)
  "$BUILD/saucer_headless" --root "$ROOT" --user-dir "$UD" --seed "$SEED" --script "$SCRIPT" --ticks $((LIMIT + 60000)) "$@" > "$OUT/$RUN.log" 2>&1 || RC=$?
  T1=$(date +%s.%N)
  echo "PTTIME $(awk "BEGIN{print $T1 - $T0}") s exit ${RC:-0}" >> "$OUT/$RUN.log"
fi
