-- The saucer.* engine API as mods see it, including error paths.
local function errs(fn, pattern)
  local ok, e = pcall(fn)
  expect(ok).to_be(false)
  if pattern then expect(tostring(e)).to_contain(pattern) end
end

describe("saucer.log / vfs / registry", function()
  it("logs with format arguments", function()
    saucer.log.info("hello %d", 1)
    saucer.log.warn("warn")
    saucer.log.error("err %s", "x")
  end)
  it("reads, lists and checks files through the mod stack", function()
    expect(saucer.vfs.exists("mod.lua")).to_be(true)
    expect(saucer.vfs.exists("nope.lua")).to_be(false)
    expect(saucer.vfs.exists("../etc/passwd")).to_be(false)
    local l = table.concat(saucer.vfs.list("meshes"), ",")
    expect(l).to_contain("saucer.lua")
    expect(#saucer.vfs.list()).to_be_greater(0)
    expect(saucer.vfs.read("nope")).to_be(nil)
  end)
  it("registry defines, extends and lists in key order", function()
    saucer.registry.define("spec_kind", "b", { v = 1 })
    saucer.registry.define("spec_kind", "a", { v = 2, nested = { x = 1 } })
    saucer.registry.extend("spec_kind", { a = { w = 3 }, c = { v = 9 } })
    expect(saucer.registry.get("spec_kind", "a").w).to_be(3)
    expect(saucer.registry.get("spec_kind", "a").v).to_be(2)
    local all = saucer.registry.all("spec_kind")
    expect(#all).to_be(3)
    expect(all[1].v).to_be(2)
    expect(saucer.registry.get("other_kind", "x")).to_be(nil)
  end)
end)

describe("saucer.rng / math", function()
  it("covers every generator method", function()
    local r = saucer.rng.new(3)
    expect(type(r:fixed())).to_be("number")
    expect(r:float() < 1).to_be(true)
    expect(r:pick({})).to_be(nil)
    expect(r:weighted({})).to_be(nil)
    expect(r:weighted({ { 0, "a" }, { 5, "b" } })).to_be("b")
    local wide = r:int(-(1 << 40), 1 << 40)
    expect(math.type(wide)).to_be("integer")
    expect(saucer.hash64("a", 1, 2.5)).to_be(saucer.hash64("a", 1, 2.5))
  end)
  it("fixed point helpers and forbidden functions", function()
    expect(saucer.math.fx(1.5)).to_be(98304)
    expect(saucer.math.fx_to(65536)).to_be(1)
    expect(saucer.math.fxmul(131072, 98304)).to_be(196608)
    expect(saucer.math.fxdiv(196608, 131072)).to_be(98304)
    expect(saucer.math.atan(0)).to_be(0)
    errs(function() return math.tan(1) end, "sandbox")
  end)
end)

describe("saucer.util read-only views", function()
  it("blocks writes and supports pairs and length", function()
    local ro = saucer.util.readonly({ a = 1, list = { 1, 2, 3 } })
    errs(function() ro.a = 2 end, "cannot mutate")
    expect(#ro.list).to_be(3)
    local n = 0
    for k, v in pairs(ro) do n = n + 1 end
    expect(n).to_be(2)
    expect(ro.list).to_be(ro.list) -- cached proxies
    errs(function() saucer.util.readonly(5) end, "table expected")
  end)
end)

describe("saucer.players / input", function()
  it("lists local players", function()
    expect(saucer.players.count()).to_be_greater(0)
    expect(saucer.players.get(1).record_index).to_be(0)
    expect(saucer.players.get(9)).to_be(nil)
  end)
  it("rebinds and persists, reports join offers and modes", function()
    expect(saucer.input.rebind(1, "scan", "key:B")).to_be(true)
    expect(saucer.input.bindings(1).scan[1]).to_be("key:B")
    expect(saucer.input.rebind(1, "scan", "bogus")).to_be(false)
    expect(saucer.input.rebind(1, "scan", "key:V")).to_be(true)
    expect(saucer.input.bindings(9)).to_be(nil)
    expect(#saucer.input.join_offers()).to_be(0)
    expect(saucer.input.device_mode(1)).to_be("kbm")
    errs(function() saucer.input.bind(1, "no_such_action", "key:A") end, "unknown action")
    errs(function() saucer.input.command({ buttons = { "turn" } }) end, "bad button")
    errs(function() saucer.input.command({ pressed = { "turn" } }) end, "bad button")
    errs(function() saucer.input.command({ axes = { shrink = 1 } }) end, "bad axis")
    local c = saucer.input.command({ buttons = { "shrink" } })
    expect(c:held("shrink")).to_be(true)
    expect(c:pressed("shrink")).to_be(false)
    errs(function() c:axis("shrink") end, "not an axis")
    errs(function() c:held("turn") end, "not a button")
    expect(saucer.input.define_action("shrink", "button")).to_be_greater(-1)
    errs(function() saucer.input.define_action("shrink", "axis") end, "cannot define")
  end)
end)

describe("saucer.physics / procgen", function()
  it("adds, removes, raycasts and counts boxes", function()
    local before = saucer.physics.count()
    local id = saucer.physics.add_box({ 1000, 0, 0 }, { 1002, 2, 2 }, 4)
    expect(saucer.physics.count()).to_be(before + 1)
    local hit = saucer.physics.raycast({ 995, 1, 1 }, { 1, 0, 0 }, 20, 4)
    expect(hit.t).to_be(5)
    expect(hit.box).to_be(id)
    expect(hit.normal[1]).to_be(-1)
    expect(saucer.physics.raycast({ 995, 1, 1 }, { -1, 0, 0 }, 20, 4)).to_be(nil)
    saucer.physics.remove(id)
    expect(saucer.physics.raycast({ 995, 1, 1 }, { 1, 0, 0 }, 20, 4)).to_be(nil)
  end)
  it("grid get, invalid sizes and empty reachability", function()
    local g = saucer.procgen.grid_new(4, 4, 4)
    expect(g:get(0, 0, 0)).to_be(0)
    expect(g:place(0, 0, 0, 1, 1, 1, 7)).to_be(true)
    expect(g:get(0, 0, 0)).to_be(7)
    expect(g:get(9, 0, 0)).to_be(-1)
    errs(function() saucer.procgen.grid_new(0, 1, 1) end, "invalid grid")
    expect(#saucer.procgen.reachable({}, {}, 1, 4)).to_be(0)
    local r = saucer.procgen.reachable({ 4, 1 }, {}, 1, 4)
    expect(r[2]).to_be(false)
  end)
end)

describe("saucer.mesh / render", function()
  it("builds all primitive kinds and rejects unknown ones", function()
    local id = saucer.mesh.build({ parts = {
      { kind = "wedge", min = { 0, 0, 0 }, max = { 1, 1, 1 }, low = 0.5 },
      { kind = "cylinder", r = 1, h = 1 },
      { kind = "cone", r = 1, r1 = 0.5, h = 1 },
      { kind = "ring", rin = 0.5, r = 1, h = 0.2 },
      { kind = "hemisphere", r = 1, h = 1 },
      { kind = "sphere", r = 1, h = 1 },
      { kind = "lathe", points = { 1, 0, 0.5, 1 } },
      { kind = "extrude", points = { 0, 0, 1, 0, 1, 1, 0, 1 }, y0 = 0, y1 = 1 },
      { kind = "extrude" },
      { kind = "stars", count = 10, r = 50 },
    } })
    expect(saucer.mesh.info(id).vertices).to_be_greater(10)
    expect(saucer.mesh.info(99999)).to_be(nil)
    errs(function() saucer.mesh.build({ parts = { { kind = "teapot" } } }) end, "unknown kind")
    errs(function() saucer.mesh.build({ parts = { 5 } }) end, "unknown kind")
    errs(function() saucer.mesh.build({ parts = { {} } }) end, "unknown kind")
    saucer.mesh.free(id)
  end)
  it("XR session starts: snapping and the affine warp are off for the headset and restored after", function()
    local function reset() saucer.render.settings({ snap = 1, dither = 1, affine = 0 }) end
    reset()
    local s = saucer.render.settings()
    expect(s.snap).to_be(true)
    expect(s.dither).to_be(true)
    expect(s.affine).to_be(false) -- the warp is opt-in
    -- each effect toggles on its own
    s = saucer.render.settings({ affine = 1 })
    expect(s.affine).to_be(true)
    expect(s.snap).to_be(true)
    s = saucer.render.settings({ snap = 0, dither = 0 })
    expect(s.snap).to_be(false)
    expect(s.dither).to_be(false)
    expect(s.affine).to_be(true)
    s = saucer.render.settings({ snap = 1, dither = 1, affine = 1 })
    -- a headset session begins with everything on in the flat settings
    saucer.test.xr({ available = 1, session = 1 })
    s = saucer.render.settings()
    expect(s.snap).to_be(false)
    expect(s.affine).to_be(false)
    expect(s.dither).to_be(true)
    saucer.test.xr({ available = 0, session = 0 })
    s = saucer.render.settings()
    expect(s.snap).to_be(true)
    expect(s.affine).to_be(true)
    reset()
  end)
  it("settings, stats, missing textures and palettes", function()
    local s = saucer.render.settings({ width = 320, height = 180, snap = 1, dither = 1 })
    expect(s.width).to_be(320)
    saucer.render.settings({ width = 480, height = 270 })
    expect(saucer.render.settings().height).to_be(270)
    local st = saucer.render.stats()
    expect(type(st.meshes)).to_be("number")
    expect(saucer.render.texture("missing.png")).to_be(1)
    expect(saucer.render.texture("mod.lua")).to_be(1)
    expect(saucer.render.palette("missing.png")).to_be(0)
  end)
end)

describe("saucer.xr / audio / save / time / mods / events", function()
  it("reports XR state and accepts haptics", function()
    expect(saucer.xr.available()).to_be(false)
    expect(saucer.xr.session()).to_be(nil)
    expect(saucer.xr.comfort().xr_safe_retro).to_be(true)
    saucer.xr.haptic("right", 0.5, 20)
  end)
  it("queues sounds", function()
    local h = saucer.audio.play("authored/sounds/pickup.wav")
    expect(h).to_be_greater(0)
    saucer.audio.stop(h)
    -- add-wider-dark: pitched notes (clamped to a sane range)
    expect(saucer.audio.play("authored/sounds/note_pluck.wav", { pitch = 1.5 })).to_be_greater(0)
    expect(saucer.audio.play("authored/sounds/note_pluck.wav", { pitch = 0.001 })).to_be_greater(0)
    expect(saucer.audio.play("authored/sounds/note_pluck.wav", { pitch = 99 })).to_be_greater(0)
    for _ = 1, 40 do saucer.audio.play("x.wav", { volume = 0.5, pan = -1 }) end
  end)
  it("saves and loads slots, rejects bad names and values", function()
    expect(saucer.save.write("spec_slot", { a = 1, b = { "x", true } })).to_be(true)
    expect(saucer.save.read("spec_slot")).to_equal({ a = 1, b = { "x", true } })
    expect(saucer.save.read("never_written")).to_be(nil)
    errs(function() saucer.save.write("../evil", 1) end, "invalid save slot")
    errs(function() saucer.save.write("", 1) end, "invalid save slot")
    errs(function() saucer.save.write("fn", { f = print }) end, "save:")
  end)
  it("time, mods and engine info", function()
    expect(saucer.time.tick()).to_be(0)
    expect(saucer.time.sim_seconds()).to_be(0)
    local mods = saucer.mods.list()
    expect(mods[1].id).to_be("base")
    expect(saucer.engine.version).to_be(_SAUCER)
    saucer.events.emit({ type = "spec" })
    errs(function() saucer.events.emit(5) end)
  end)
end)

describe("saucer.test outside a game script", function()
  it("snapshots, restores and hashes", function()
    local h = saucer.test.state_hash()
    local snap = saucer.test.snapshot()
    saucer.test.state().spec_marker = 1
    expect(saucer.test.state_hash() ~= h).to_be(true)
    expect(saucer.test.restore(snap)).to_be(true)
    expect(saucer.test.state_hash()).to_be(h)
    expect(saucer.test.restore("garbage")).to_be(false)
  end)
  it("drives touch, XR and viewports; waits need a game script", function()
    saucer.test.touch("down", 1, 0.1, 0.6)
    saucer.test.touch("move", 1, 0.15, 0.5)
    saucer.test.touch("up", 1)
    saucer.test.xr({ available = 1, session = 2, head_fwd = { 0, 0, 1 }, controls = { trigger_r = 1, bogus = 1 } })
    expect(saucer.xr.session()).to_be("standing")
    saucer.test.xr({ available = 0, session = 0, controls = { trigger_r = 0 } })
    saucer.test.viewports(9)
    saucer.test.viewports(0)
    saucer.test.viewports(1)
    expect(saucer.test.audio_count()).to_be_greater(0)
    errs(function() saucer.test.wait(1) end, "only work inside")
    errs(function() saucer.test.press(9, "shrink") end, "bad player")
    errs(function() saucer.test.axis(1, "shrink", 1) end, "not an axis")
    errs(function() saucer.test.assert(false, "boom") end, "boom")
    errs(function() saucer.test.assert(false) end, "assertion failed")
    saucer.test.assert(true)
  end)
end)
