-- add-presentation-packaging: the sound director. Render-side only: it reads
-- the state, never writes it, so replays and hashes are untouched.
--   * one-shots: the sim's per-player fx list (game.fx) plus events the
--     renderer can see on its own (a door starting to slide, a menu row
--     changing, the saucer going into or out of your pocket)
--   * loops: engine hum, tractor beam, holodeck, station crowd and derelict
--     hall ambience, each faded towards a target level every frame and only
--     sent to the mixer when the level really moves
-- Sounds are code-generated by tools/artpipe/artpipe.py (CC BY 4.0).
local M = {}

local S = "authored/sounds/"
M.SOUNDS = {
  shrink = S .. "shrink.wav", grow = S .. "grow.wav", tractor = S .. "tractor.wav",
  pickup = S .. "pickup.wav", denied = S .. "denied.wav", bank = S .. "bank.wav",
  echo = S .. "echo.wav", scan = S .. "scan.wav", jam = S .. "jam.wav", alert = S .. "alert.wav",
  locked = S .. "locked.wav", hit = S .. "hit.wav", door = S .. "door.wav", click = S .. "click.wav",
  coin = S .. "coin.wav",
}
M.LOOPS = {
  engine = S .. "engine_hum.wav", beam = S .. "beam_loop.wav", holo = S .. "holo_loop.wav",
  station = S .. "station_loop.wav", derelict = S .. "derelict_loop.wav",
}
M.LOOP_ORDER = { "engine", "beam", "holo", "station", "derelict" }
M.FADE = 0.08      -- per frame, towards the target level
M.EPS = 0.02       -- smallest level change worth a mixer update
M.MASTER = 1.0     -- scales everything (mods and settings may change it)

local heard = {}   -- per player: last fx tick played
local seen = {}    -- per player: what the renderer saw last frame
local live = {}    -- loop name -> { handle =, level =, sent = }
M.live = live

function M.reset()
  for k in pairs(heard) do heard[k] = nil end
  for k in pairs(seen) do seen[k] = nil end
  for name, l in pairs(live) do
    if l.handle then saucer.audio.stop(l.handle) end
    live[name] = nil
  end
end

local function play(name, volume)
  local path = M.SOUNDS[name]
  if not path then return nil end
  return saucer.audio.play(path, { volume = (volume or 0.8) * M.MASTER })
end
M.play = play

-- the sim's fx for player p since the last frame
function M.fx(state, p)
  local last = heard[p.index] or -1
  if state.tick < last then last = -1 end
  local n = 0
  for _, f in ipairs(p.fx or {}) do
    if f.tick > last and M.SOUNDS[f.sound] then
      play(f.sound, 0.8)
      n = n + 1
    end
  end
  heard[p.index] = state.tick
  return n
end

-- events the renderer notices by comparing with last frame -> list of names
function M.events(state, p)
  local was = seen[p.index]
  local now = { doors = {}, sel = p.panel and p.panel.sel, kind = p.panel and p.panel.kind,
                coin = (p.station and p.station.coin) or (p.excursion and p.excursion.coin), mode = p.mode }
  for i, d in ipairs(p.doors or {}) do now.doors[i] = d end
  seen[p.index] = now
  local out = {}
  if not was then return out end
  for i, d in ipairs(now.doors) do
    local before = was.doors[i] or 0
    if (before <= 0 and d > 0) or (before >= 1 and d < 1) then out[#out + 1] = "door" end
  end
  if now.sel and was.sel and now.kind == was.kind and now.sel ~= was.sel then out[#out + 1] = "click" end
  if now.coin ~= was.coin and (now.coin == "pocket" or now.coin == "hand") then out[#out + 1] = "coin" end
  return out
end

-- how loud each loop should be right now (0 = off)
function M.levels(state, p)
  local lv = { engine = 0, beam = 0, holo = 0, station = 0, derelict = 0 }
  if p.mode == "foot" and p.excursion then
    -- add-on-foot-excursions: no engine, just the derelict around you
    lv.derelict = 0.6
    return lv
  end
  if p.mode == "foot" then
    lv.station = 0.55
    return lv
  end
  if p.holo_run then
    lv.holo = 0.5
    return lv
  end
  local ship = p.ship or {}
  local v = ship.vel or { 0, 0, 0 }
  local speed = math.sqrt(v[1] * v[1] + v[2] * v[2] + v[3] * v[3])
  local base = p.mode == "helm" and 0.3 or 0.18
  lv.engine = base + math.min(0.35, speed / 40)
  if p.tractor then lv.beam = 0.5 end
  if (p.site or 0) ~= 0 then lv.derelict = 0.35 end
  return lv
end

-- fade the loops towards their levels; start and stop them as needed
function M.loops(levels)
  local sent = 0
  for _, name in ipairs(M.LOOP_ORDER) do
    local want = (levels[name] or 0) * M.MASTER
    local l = live[name]
    if not l and want > 0 then
      l = { level = 0, sent = 0 }
      live[name] = l
    end
    if l then
      l.level = l.level + (want - l.level) * M.FADE
      if want == 0 and l.level < M.EPS then
        if l.handle then saucer.audio.stop(l.handle) end
        live[name] = nil
        sent = sent + 1
      elseif not l.handle then
        l.handle = saucer.audio.play(M.LOOPS[name], { volume = l.level, loop = true })
        l.sent = l.level
        sent = sent + 1
      elseif math.abs(l.level - l.sent) >= M.EPS then
        saucer.audio.set(l.handle, { volume = l.level })
        l.sent = l.level
        sent = sent + 1
      end
    end
  end
  return sent
end

-- once per frame for each local player's own view; loops follow the first
function M.update(state, p, first)
  local n = M.fx(state, p)
  for _, name in ipairs(M.events(state, p)) do
    play(name, name == "click" and 0.5 or 0.7)
    n = n + 1
  end
  if first then n = n + M.loops(M.levels(state, p)) end
  return n
end

return M
